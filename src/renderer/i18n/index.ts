export type LocaleDict = typeof translations['zh-CN'];

export function t(locale: string, path: string): string {
  const localeDict = translations[locale as keyof typeof translations] || translations['en'];
  const keys = path.split('.');
  let value: any = localeDict;
  for (const key of keys) {
    if (value && typeof value === 'object') {
      value = value[key];
    } else {
      return path; // fallback
    }
  }
  return typeof value === 'string' ? value : path;
}
